create table if not exists public.game_users (
  id uuid primary key default gen_random_uuid(),
  username text not null,
  username_key text generated always as (lower(btrim(username))) stored,
  full_name text not null,
  password_salt text not null,
  password_hash text not null,
  is_admin boolean not null default false,
  profile jsonb not null default '{}'::jsonb,
  progress jsonb not null default '{"tutorialCompleted":false,"unlockedPhases":[1],"collectedEvidence":[],"answers":[],"fieldNotes":{},"finalReview":null,"badges":[]}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint game_users_username_key_unique unique (username_key),
  constraint game_users_username_length check (char_length(btrim(username)) between 2 and 40)
);

create table if not exists public.game_sessions (
  token_hash text primary key,
  user_id uuid not null references public.game_users(id) on delete cascade,
  expires_at timestamptz not null,
  created_at timestamptz not null default now()
);

create index if not exists game_sessions_user_id_idx on public.game_sessions(user_id);
create index if not exists game_sessions_expires_at_idx on public.game_sessions(expires_at);

create table if not exists public.game_reviews (
  id bigint generated by default as identity primary key,
  user_id uuid references public.game_users(id) on delete set null,
  reviewer_name text not null,
  rating smallint not null check (rating between 1 and 5),
  mechanics text not null default '',
  immersion text not null default '',
  improvements text not null default '',
  submitted_at timestamptz not null default now()
);

create index if not exists game_reviews_user_id_idx on public.game_reviews(user_id);
create index if not exists game_reviews_submitted_at_idx on public.game_reviews(submitted_at desc);

alter table public.game_users enable row level security;
alter table public.game_sessions enable row level security;
alter table public.game_reviews enable row level security;

revoke all on table public.game_users from anon, authenticated;
revoke all on table public.game_sessions from anon, authenticated;
revoke all on table public.game_reviews from anon, authenticated;

